/**
 * The sign-in and registration pages in the languages of Belgium plus English, like asafarim.site:
 * nl (default), fr, en, de. The choice comes from `?lang=`, then the `breinhap-lang` cookie, then the
 * browser's Accept-Language. The rest of the management workspace is in Dutch for now.
 */

export const LANGUAGES = ["nl", "fr", "en", "de"];
export const LANGUAGE_NAMES = { nl: "Nederlands", fr: "Français", en: "English", de: "Deutsch" };
export const LANG_COOKIE = "breinhap-lang";

export function localeOf(req, url) {
	const asked = url?.searchParams.get("lang");
	if (LANGUAGES.includes(asked)) return asked;
	const cookie = /(?:^|;\s*)breinhap-lang=([a-z]{2})(?:;|$)/.exec(req.headers.cookie ?? "")?.[1];
	if (LANGUAGES.includes(cookie)) return cookie;
	for (const part of String(req.headers["accept-language"] ?? "").split(",")) {
		const tag = part.trim().slice(0, 2).toLowerCase();
		if (LANGUAGES.includes(tag)) return tag;
	}
	return "nl";
}
/**
 * The language cookie. On breinhap.com's hosts it is set for the parent domain, so a choice made on the website
 * holds here and the other way round; anywhere else (localhost, tests) it stays on the host.
 */
export const langCookie = (lang, host = "") => {
	const name = String(host).replace(/:\d+$/, "").toLowerCase();
	const shared = name === "breinhap.com" || name.endsWith(".breinhap.com") ? "; Domain=breinhap.com" : "";
	return `${LANG_COOKIE}=${lang}; Path=/; Secure; SameSite=Lax; Max-Age=31536000${shared}`;
};

