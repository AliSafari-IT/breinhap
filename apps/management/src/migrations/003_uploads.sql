-- breinhap#29: uploaded teaching material and images. The bytes live in a private object store under a
-- generated key; this table holds who uploaded what, its declared source and licence, and where it
-- stands in the quarantine: every file starts `quarantined`, and only a clean scan makes it `clean`
-- (the only state that may be read or served). Contents and names are never logged.
CREATE TABLE uploads (
  workspace_id text NOT NULL REFERENCES workspaces (id),
  id uuid NOT NULL,
  uploader_sub text NOT NULL CHECK (char_length(uploader_sub) BETWEEN 1 AND 400),
  -- the cleaned display name (no path, no control characters); cleared when the file is deleted
  file_name text CHECK (char_length(file_name) BETWEEN 1 AND 120),
  kind text NOT NULL CHECK (kind IN ('pdf', 'docx', 'png', 'jpeg', 'webp')),
  media_type text NOT NULL,
  size_bytes integer NOT NULL CHECK (size_bytes BETWEEN 1 AND 10485760),
  sha256 text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  -- generated by the server, never derived from the file name
  storage_key text NOT NULL UNIQUE CHECK (storage_key ~ '^uploads/[0-9a-f-]{36}$'),
  status text NOT NULL DEFAULT 'quarantined' CHECK (status IN ('quarantined', 'clean', 'rejected', 'deleted')),
  -- why it was rejected: a short code (infected, scan_timeout, …), never the scanner's detail
  reason text CHECK (reason ~ '^[a-z_]{1,40}$'),
  source_kind text NOT NULL CHECK (source_kind IN ('own', 'school', 'publisher', 'open_licence', 'other')),
  licence text NOT NULL CHECK (licence IN ('own_work', 'permission', 'cc_by', 'cc_by_sa', 'cc0', 'public_domain', 'unknown')),
  source_note text CHECK (char_length(source_note) <= 300),
  scan_attempts smallint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  scanned_at timestamptz,
  deleted_at timestamptz,
  PRIMARY KEY (workspace_id, id),
  CHECK ((status = 'deleted') = (deleted_at IS NOT NULL)),
  CHECK (status <> 'deleted' OR file_name IS NULL)
);
CREATE INDEX uploads_uploader ON uploads (workspace_id, uploader_sub, created_at DESC) WHERE status <> 'deleted';
CREATE INDEX uploads_quarantine ON uploads (created_at) WHERE status = 'quarantined';

-- A clean file never goes back to quarantine, and a deleted one never comes back.
CREATE FUNCTION uploads_transition() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status = 'deleted' THEN
    RAISE EXCEPTION 'a deleted upload cannot change';
  END IF;
  IF OLD.status = 'clean' AND NEW.status NOT IN ('clean', 'deleted') THEN
    RAISE EXCEPTION 'a clean upload can only be deleted';
  END IF;
  IF OLD.status = 'rejected' AND NEW.status NOT IN ('rejected', 'deleted') THEN
    RAISE EXCEPTION 'a rejected upload can only be deleted';
  END IF;
  IF NEW.storage_key <> OLD.storage_key OR NEW.sha256 <> OLD.sha256 OR NEW.uploader_sub <> OLD.uploader_sub
     OR NEW.size_bytes <> OLD.size_bytes OR NEW.kind <> OLD.kind THEN
    RAISE EXCEPTION 'an upload''s identity cannot change';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER uploads_transition BEFORE UPDATE ON uploads FOR EACH ROW EXECUTE FUNCTION uploads_transition();
