// Bundles the country & language selector (React + @asafarim/country-language-selector) into one
// self-hosted script and stylesheet, so no image needs a build step or React. Both breinhap.com (apps/web) and
// management serve the two files from apps/site/public, next to the other shared assets:
//
//   pnpm --filter @breinhap/management build:selector
//
// test/locale-selector.test.mjs fails while the committed bundle differs from a fresh build.
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const here = new URL("..", import.meta.url);
export const OUTPUT = new URL("../site/public/locale-selector.js", here);
export const STYLES = new URL("../site/public/locale-selector.css", here);

/** `{ js, css }` as they should be committed, or null when the build tools aren't installed. */
export async function render() {
	let esbuild;
	try {
		esbuild = createRequire(import.meta.url)("esbuild");
	} catch {
		return null;
	}
	const result = await esbuild.build({
		entryPoints: [new URL("src/account/locale-selector.client.jsx", here).pathname],
		bundle: true,
		minify: true,
		format: "iife",
		target: "es2020",
		jsx: "automatic",
		define: { "process.env.NODE_ENV": '"production"' },
		legalComments: "none",
		write: false,
		logLevel: "silent",
	});
	const banner = "/* breinhap (web + management): @asafarim/country-language-selector 0.5.3 + React 19.3.0 (MIT). Generated by scripts/build-locale-selector.mjs; do not edit. */\n";
	const css = await readFile(createRequire(import.meta.url).resolve("@asafarim/country-language-selector/styles.css"), "utf8");
	return { js: banner + result.outputFiles[0].text, css: `/* @asafarim/country-language-selector 0.5.3 styles (MIT). Generated; do not edit. */\n${css}` };
}

if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
	const built = await render();
	if (!built) throw new Error("esbuild is not installed: run pnpm install at the repository root");
	await writeFile(OUTPUT, built.js);
	await writeFile(STYLES, built.css);
	console.log("Wrote", OUTPUT.pathname, `${(built.js.length / 1024).toFixed(0)} KiB`, "and", STYLES.pathname);
}
